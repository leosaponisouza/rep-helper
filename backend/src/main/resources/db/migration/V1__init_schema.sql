-- 6. TASKS & ASSIGNEES
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    house_id UUID NOT NULL REFERENCES houses(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    due_date TIMESTAMP WITH TIME ZONE,
    category VARCHAR(80),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'OVERDUE', 'CANCELLED')),
    created_by_uid UUID REFERENCES users(uid) ON DELETE SET NULL,
    recurring BOOLEAN NOT NULL DEFAULT FALSE,
    recurrence_type VARCHAR(20)
        CHECK (recurrence_type IN ('DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
    recurrence_interval INTEGER DEFAULT 1 CHECK (recurrence_interval IS NULL OR recurrence_interval >= 1),
    recurrence_end_date TIMESTAMP WITH TIME ZONE,
    parent_task_id BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_tasks_house_due_status
    ON tasks (house_id, status, due_date);

CREATE TABLE task_assignees (
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    user_uid UUID NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
    PRIMARY KEY (task_id, user_uid)
);

CREATE INDEX idx_task_assignees_user
    ON task_assignees (user_uid);

-- 7. EXPENSES, INCOMES & BALANCE ADJUSTMENTS
